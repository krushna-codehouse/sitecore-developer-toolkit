import fs from 'node:fs';
import path from 'node:path';
import { toolkitConfig, type ToolkitConfig } from '../../toolkit.config';
import { fromRoot, readFileIfExists, relativeToRoot } from './paths';
import type { CheckGroup, CheckResult } from './types';

const PASCAL_CASE = /^[A-Z][A-Za-z0-9]*$/;
const FOLDER_SEGMENT = /^[a-z0-9][a-z0-9-]*$/;

export interface ComponentInfo {
  /** Rendering name, which must match the rendering's component name in Sitecore. */
  name: string;
  /** Folder relative to the components dir, e.g. "marketing/PromoCard". */
  relativeDir: string;
  absoluteDir: string;
  files: string[];
}

export interface ComponentReport extends ComponentInfo {
  inMap: boolean;
  results: CheckResult[];
}

// ---------------------------------------------------------------------------
// Discovery
// ---------------------------------------------------------------------------

/** A folder is a component when it contains `<FolderName>.tsx`. Other folders are treated as categories. */
export function discoverComponents(config: ToolkitConfig = toolkitConfig): ComponentInfo[] {
  const root = fromRoot(config.componentsDir);
  const found: ComponentInfo[] = [];

  const visit = (dir: string) => {
    if (!fs.existsSync(dir)) return;
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      if (!entry.isDirectory() || entry.name.startsWith('_') || entry.name === '__tests__') continue;
      const absoluteDir = path.join(dir, entry.name);
      const files = fs.readdirSync(absoluteDir).filter((f) => fs.statSync(path.join(absoluteDir, f)).isFile());
      if (files.includes(`${entry.name}.tsx`)) {
        found.push({
          name: entry.name,
          relativeDir: path.relative(root, absoluteDir).split(path.sep).join('/'),
          absoluteDir,
          files,
        });
      } else {
        visit(absoluteDir);
      }
    }
  };

  visit(root);
  return found.sort((a, b) => a.relativeDir.localeCompare(b.relativeDir));
}

/** Rendering names registered in the generated component map. */
export function readComponentMap(config: ToolkitConfig = toolkitConfig): string[] | undefined {
  const source = readFileIfExists(fromRoot(config.componentMapFile));
  if (source === undefined) return undefined;
  return [...source.matchAll(/\[\s*'([^']+)'\s*,/g)].map((m) => m[1]);
}

// ---------------------------------------------------------------------------
// Component map generation
// ---------------------------------------------------------------------------

export function buildComponentMapSource(components: ComponentInfo[]): string {
  const used = new Map<string, number>();
  const entries = components.map((c) => {
    const count = used.get(c.name) ?? 0;
    used.set(c.name, count + 1);
    const identifier = count === 0 ? c.name : `${c.name}${count + 1}`;
    return { ...c, identifier };
  });

  const imports = entries.map((e) => `import ${e.identifier} from './${e.relativeDir}';`).join('\n');
  const rows = entries.map((e) => `  ['${e.name}', ${e.identifier}],`).join('\n');

  return `// AUTO-GENERATED by \`npm run sc:component:map\`. Do not edit by hand.
// Keys must match the component (rendering) names configured in Sitecore.
import type { ComponentType } from 'react';
${imports}

// eslint-disable-next-line @typescript-eslint/no-explicit-any
export const componentMap = new Map<string, ComponentType<any>>([
${rows}
]);

export default componentMap;
`;
}

export function writeComponentMap(config: ToolkitConfig = toolkitConfig): { file: string; count: number } {
  const components = discoverComponents(config);
  const file = fromRoot(config.componentMapFile);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, buildComponentMapSource(components));
  return { file: relativeToRoot(file), count: components.length };
}

// ---------------------------------------------------------------------------
// Scaffolding
// ---------------------------------------------------------------------------

export function validateComponentPath(input: string): string | undefined {
  const segments = input.replace(/\\/g, '/').split('/').filter(Boolean);
  if (segments.length === 0) return 'A component name is required.';
  const name = segments[segments.length - 1];
  if (!PASCAL_CASE.test(name)) return `"${name}" must be PascalCase, e.g. HeroBanner.`;
  const badFolder = segments.slice(0, -1).find((s) => !FOLDER_SEGMENT.test(s));
  if (badFolder) return `Folder "${badFolder}" must be lower-case kebab-case, e.g. marketing/HeroBanner.`;
  return undefined;
}

export interface CreateComponentOptions {
  dryRun?: boolean;
  /** Regenerate the component map after creating files (default true). */
  updateMap?: boolean;
  templatesDir?: string;
  config?: ToolkitConfig;
}

export interface CreateComponentResult {
  name: string;
  dir: string;
  files: string[];
  dryRun: boolean;
}

export function templateTokens(name: string): Record<string, string> {
  const words = name.replace(/([a-z0-9])([A-Z])/g, '$1 $2').replace(/([A-Z])([A-Z][a-z])/g, '$1 $2');
  return {
    name,
    camelName: name.charAt(0).toLowerCase() + name.slice(1),
    kebabName: words.toLowerCase().replace(/\s+/g, '-'),
    titleName: words,
  };
}

export function renderTemplate(template: string, tokens: Record<string, string>): string {
  // Only known tokens are replaced, so JSX such as style={{ ... }} is left untouched.
  return template.replace(/\{\{(\w+)\}\}/g, (match, key: string) => tokens[key] ?? match);
}

export function createComponent(input: string, options: CreateComponentOptions = {}): CreateComponentResult {
  const config = options.config ?? toolkitConfig;
  const error = validateComponentPath(input);
  if (error) throw new Error(error);

  const segments = input.replace(/\\/g, '/').split('/').filter(Boolean);
  const name = segments[segments.length - 1];
  const dir = fromRoot(config.componentsDir, ...segments);

  if (fs.existsSync(dir)) throw new Error(`Component folder already exists: ${relativeToRoot(dir)}`);

  const duplicate = discoverComponents(config).find((c) => c.name === name);
  if (duplicate) {
    throw new Error(
      `A component named ${name} already exists at ${duplicate.relativeDir}. Rendering names must be unique.`,
    );
  }

  const templatesDir = options.templatesDir ?? fromRoot(config.templatesDir);
  if (!fs.existsSync(templatesDir)) throw new Error(`Templates folder not found: ${templatesDir}`);

  const tokens = templateTokens(name);
  const templates = fs.readdirSync(templatesDir).filter((f) => f.endsWith('.tpl'));
  const outputs = templates.map((template) => ({
    file: path.join(dir, template.replace(/\.tpl$/, '').replace(/__name__/g, name)),
    content: renderTemplate(fs.readFileSync(path.join(templatesDir, template), 'utf8'), tokens),
  }));

  if (!options.dryRun) {
    fs.mkdirSync(dir, { recursive: true });
    for (const output of outputs) fs.writeFileSync(output.file, output.content);
    if (options.updateMap !== false) writeComponentMap(config);
  }

  return {
    name,
    dir: relativeToRoot(dir),
    files: outputs.map((o) => relativeToRoot(o.file)),
    dryRun: Boolean(options.dryRun),
  };
}

// ---------------------------------------------------------------------------
// Diagnostics
// ---------------------------------------------------------------------------

export function inspectComponents(config: ToolkitConfig = toolkitConfig): {
  components: ComponentReport[];
  mapEntries: string[] | undefined;
} {
  const components = discoverComponents(config);
  const mapEntries = readComponentMap(config);
  const mapSet = new Set(mapEntries ?? []);

  const reports = components.map<ComponentReport>((component) => {
    const results: CheckResult[] = [];
    const expand = (pattern: string) => pattern.replace(/\{name\}/g, component.name);

    if (!PASCAL_CASE.test(component.name)) {
      results.push({ id: 'naming', title: 'Naming', status: 'fail', message: 'Folder name must be PascalCase.' });
    }

    const missingRequired = config.components.requiredFiles.map(expand).filter((f) => !component.files.includes(f));
    const missingRecommended = config.components.recommendedFiles
      .map(expand)
      .filter((f) => !component.files.includes(f));

    results.push({
      id: 'files',
      title: 'Required files',
      status: missingRequired.length ? 'fail' : missingRecommended.length ? 'warn' : 'pass',
      message: missingRequired.length
        ? `Missing ${missingRequired.join(', ')}`
        : missingRecommended.length
          ? `Missing recommended ${missingRecommended.join(', ')}`
          : 'All files present',
    });

    const source = fs.readFileSync(path.join(component.absoluteDir, `${component.name}.tsx`), 'utf8');

    if (!/export\s+default\s/.test(source)) {
      results.push({
        id: 'default-export',
        title: 'Default export',
        status: 'fail',
        message: 'The component map imports the default export, but none was found.',
      });
    }

    // Heuristic: rendering `fields.x.value` directly bypasses the SDK field
    // components, which breaks inline editing in Pages.
    const rawValues = [...source.matchAll(/\{[^{}]*fields\??\.\w+\??\.value[^{}]*\}/g)].map((m) => m[0].trim());
    if (rawValues.length) {
      results.push({
        id: 'raw-field-values',
        title: 'Editing support',
        status: 'warn',
        message:
          'Field values are rendered directly. Use <Text>, <RichText>, <Image> or <Link> so authors can edit inline.',
        details: rawValues.slice(0, 5),
      });
    }

    if (/\bfields\??\./.test(source) && !/!\s*fields\b|fields\s*\?\?|fields\s*===?\s*(undefined|null)/.test(source)) {
      results.push({
        id: 'datasource-guard',
        title: 'Missing datasource handling',
        status: 'warn',
        message: 'No guard for a missing datasource was found. Renderings without a datasource will throw.',
      });
    }

    const inMap = mapSet.has(component.name);
    results.push({
      id: 'registered',
      title: 'Component map',
      status: inMap ? 'pass' : 'fail',
      message: inMap ? 'Registered' : 'Not registered. Run `npm run sc:component:map`.',
    });

    return { ...component, inMap, results };
  });

  return { components: reports, mapEntries };
}

export function checkComponents(config: ToolkitConfig = toolkitConfig): CheckGroup {
  const { components, mapEntries } = inspectComponents(config);
  const results: CheckResult[] = [];

  if (components.length === 0) {
    results.push({
      id: 'none',
      title: 'Components',
      status: 'warn',
      message: `No components found in ${config.componentsDir}.`,
    });
  }

  for (const component of components) {
    const problems = component.results.filter((r) => r.status !== 'pass');
    const status = problems.some((p) => p.status === 'fail') ? 'fail' : problems.length ? 'warn' : 'pass';
    results.push({
      id: `component-${component.relativeDir}`,
      title: component.relativeDir,
      status,
      message: problems.length ? problems.map((p) => p.message).join(' ') : 'OK',
      details: problems.flatMap((p) => p.details ?? []),
    });
  }

  // Duplicate rendering names (e.g. two "Card" components in different folders)
  const byName = new Map<string, string[]>();
  for (const c of components) byName.set(c.name, [...(byName.get(c.name) ?? []), c.relativeDir]);
  const duplicates = [...byName.entries()].filter(([, dirs]) => dirs.length > 1);
  if (duplicates.length) {
    results.push({
      id: 'duplicate-names',
      title: 'Unique rendering names',
      status: 'fail',
      message: 'Several components share the same rendering name.',
      details: duplicates.map(([name, dirs]) => `${name}: ${dirs.join(', ')}`),
    });
  }

  // Stale map entries pointing to deleted components
  if (mapEntries === undefined) {
    results.push({
      id: 'map-missing',
      title: 'Component map',
      status: 'fail',
      message: `${config.componentMapFile} not found. Run \`npm run sc:component:map\`.`,
    });
  } else {
    const names = new Set(components.map((c) => c.name));
    const stale = mapEntries.filter((n) => !names.has(n));
    if (stale.length) {
      results.push({
        id: 'map-stale',
        title: 'Stale component map entries',
        status: 'fail',
        message: 'The component map references components that no longer exist.',
        details: stale,
      });
    }
  }

  return { id: 'components', title: 'Components', results };
}
